#!/usr/bin/env node
/**
 * Generates src/assets/generated/*.ts from the Protomaps basemaps-assets repo and a z0-3 world
 * PMTiles. Output is embedded as base64 and copied to documents/style on first launch
 * (docs/MAP_ARCHITECTURE.md 3.2; ADR 0001 explains why not Metro assets).
 *
 *   node scripts/gen-style-assets.mjs <basemaps-assets dir> <world-base.pmtiles>
 */
import { createRequire } from 'node:module';
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const here = dirname(fileURLToPath(import.meta.url));
const [assetsDir, worldPath] = process.argv.slice(2);
if (!assetsDir || !worldPath) {
  console.error('usage: gen-style-assets.mjs <basemaps-assets dir> <world-base.pmtiles>');
  process.exit(2);
}

const { layers, namedFlavor } = require('@protomaps/basemaps');
const flavor = process.env.FLAVOR ?? 'light';

// Latin, Latin extended, combining marks, Cyrillic, extra Latin, punctuation, letterlike symbols.
const RANGES = ['0-255', '256-511', '512-767', '768-1023', '1024-1279', '7680-7935', '8192-8447', '8448-8703'];

const fonts = new Set();
for (const l of layers('x', namedFlavor(flavor), { lang: 'en' })) {
  const tf = l.layout?.['text-font'];
  if (Array.isArray(tf)) {
    const walk = v => (Array.isArray(v) ? v.forEach(walk) : typeof v === 'string' && v.startsWith('Noto') && fonts.add(v));
    walk(tf);
  }
}
// Overlay layers (markers, labels) use this stack as well.
fonts.add('Noto Sans Regular');

const files = {};
for (const font of fonts) {
  for (const r of RANGES) {
    const p = join(assetsDir, 'fonts', font, `${r}.pbf`);
    if (!existsSync(p)) {
      console.error(`missing glyph range ${font}/${r}.pbf`);
      process.exit(1);
    }
    files[`fonts/${font}/${r}.pbf`] = readFileSync(p).toString('base64');
  }
}
for (const f of [`${flavor}.json`, `${flavor}.png`, `${flavor}@2x.json`, `${flavor}@2x.png`]) {
  files[`sprites/${flavor}/${f.replace(flavor, 'sprite')}`] = readFileSync(join(assetsDir, 'sprites', 'v4', f)).toString('base64');
}

const out = join(here, '..', 'src', 'assets', 'generated');
mkdirSync(out, { recursive: true });
const banner = '// GENERATED by scripts/gen-style-assets.mjs. Do not edit.\n/* eslint-disable */\n';
writeFileSync(
  join(out, 'styleAssets.ts'),
  `${banner}export const STYLE_ASSETS_VERSION = ${JSON.stringify(`${flavor}-v1`)};\nexport const STYLE_FONTS = ${JSON.stringify([...fonts])};\nexport const STYLE_ASSETS: Record<string, string> = ${JSON.stringify(files)};\n`,
);
writeFileSync(
  join(out, 'worldBase.ts'),
  `${banner}export const WORLD_BASE_VERSION = 'z0-3-20261029';\nexport const WORLD_BASE_BASE64 = ${JSON.stringify(readFileSync(worldPath).toString('base64'))};\n`,
);
console.log(`fonts: ${[...fonts].join(', ')}\nfiles: ${Object.keys(files).length}`);
